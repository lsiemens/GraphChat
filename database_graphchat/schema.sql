CREATE SCHEMA graphchat;

--- Types

CREATE DOMAIN graphchat.graph_id AS TEXT
    CHECK (VALUE ~ '^[0-9a-f]{32}$');

CREATE DOMAIN graphchat.node_id AS TEXT
    CHECK (VALUE ~ '^[0-9a-f]{64}$');

CREATE DOMAIN graphchat.string AS TEXT
    CHECK (LENGTH(BTRIM(VALUE)) > 0);

CREATE DOMAIN graphchat.uinteger AS INTEGER
    CHECK (VALUE >= 0);

CREATE DOMAIN graphchat.unumeric AS NUMERIC
    CHECK (VALUE >= 0);

CREATE TYPE graphchat.node_usage AS (
    cached_prompt_text_tokens graphchat.uinteger,
    prompt_tokens graphchat.uinteger,
    reasoning_tokens graphchat.uinteger,
    completion_tokens graphchat.uinteger,
    cost_usd graphchat.unumeric
);

--- Tables: Nodes
CREATE TABLE graphchat.nodes (
    node_id graphchat.node_id,
    request_timestamp TIMESTAMPTZ NOT NULL,
    request graphchat.string NOT NULL,
    reply_timestamp TIMESTAMPTZ NOT NULL,
    reply graphchat.string NOT NULL,
    model graphchat.string NOT NULL,
    usage graphchat.node_usage NOT NULL,
    CHECK (
        (usage).cached_prompt_text_tokens IS NOT NULL
        AND (usage).prompt_tokens IS NOT NULL
        AND (usage).reasoning_tokens IS NOT NULL
        AND (usage).completion_tokens IS NOT NULL
    ),
    PRIMARY KEY (node_id)
);

CREATE TABLE graphchat.nodes_upstream (
    node_id graphchat.node_id
        REFERENCES graphchat.nodes(node_id) ON DELETE CASCADE,
    upstream_order INTEGER
        CHECK (upstream_order >= 0),
    upstream_id graphchat.node_id NOT NULL
        REFERENCES graphchat.nodes(node_id) ON DELETE RESTRICT,
    CHECK (upstream_id <> node_id),
    UNIQUE (node_id, upstream_id),
    PRIMARY KEY (node_id, upstream_order)
);

CREATE TABLE graphchat.nodes_context (
    node_id graphchat.node_id
        REFERENCES graphchat.nodes(node_id) ON DELETE CASCADE,
    context_order INTEGER
        CHECK (context_order >= 0),
    context_id graphchat.node_id NOT NULL
        REFERENCES graphchat.nodes(node_id) ON DELETE RESTRICT,
    CHECK (context_id <> node_id),
    UNIQUE (node_id, context_id),
    PRIMARY KEY (node_id, context_order)
);

--- Tables: Graphs

CREATE TABLE graphchat.graphs (
    graph_id graphchat.graph_id,
    PRIMARY KEY (graph_id)
);

CREATE TABLE graphchat.graphs_nodes (
    graph_id graphchat.graph_id
        REFERENCES graphchat.graphs(graph_id) ON DELETE CASCADE,
    node_id graphchat.node_id
        REFERENCES graphchat.nodes(node_id) ON DELETE CASCADE,
    PRIMARY KEY (graph_id, node_id)
);

--- Immutability:
CREATE FUNCTION graphchat.prevent_update()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Table %.% is immutable (nodes and their core data can not be updated)',
        TG_TABLE_SCHEMA, TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_nodes_immutable
    BEFORE UPDATE ON graphchat.nodes
    FOR EACH ROW
        EXECUTE FUNCTION graphchat.prevent_update();

CREATE TRIGGER trigger_nodes_upstream
    BEFORE UPDATE ON graphchat.nodes_upstream
    FOR EACH ROW
        EXECUTE FUNCTION graphchat.prevent_update();

CREATE TRIGGER trigger_nodes_context
    BEFORE UPDATE ON graphchat.nodes_context
    FOR EACH ROW
        EXECUTE FUNCTION graphchat.prevent_update();

--- Indexes
CREATE INDEX index_nodes_upstream_upstream_id on graphchat.nodes_upstream (upstream_id);

--- Comments
COMMENT ON TABLE graphchat.nodes IS 'Immutable graphchat node containing a request and LLM reply, node_id is a SHA256 hash of the node generated by engine_graphchat.';
COMMENT ON TABLE graphchat.nodes_upstream IS 'Orderd set of direct upstream (parent) node.';
COMMENT ON TABLE graphchat.nodes_context IS 'Topologically orderd set of upstream traversable nodes, this defines the context supplied to the LLM.';
COMMENT ON TABLE graphchat.graphs IS 'Avaliable graphs.';
COMMENT ON TABLE graphchat.graphs_nodes IS 'Terminal nodes of the graph. Any node included here or in the upstream traversible graph of the node should be treated as being included in the graph.';
